#!/usr/bin/env python3
import gzip
import os

def get_project_dir():
    # If run inside PlatformIO's SCons environment
    import_fn = globals().get("Import")
    if import_fn:
        try:
            import_fn("env")
            env = globals().get("env")
            if env and "PROJECT_DIR" in env:
                return env["PROJECT_DIR"]
        except Exception:
            pass
    if "__file__" in globals():
        return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.getcwd()

def build_portal_header():
    project_dir = get_project_dir()
    source_html = os.path.join(project_dir, "app", "index.html")
    output_header = os.path.join(project_dir, "include", "portal_html.h")

    if not os.path.exists(source_html):
        print(f"[build_html] Error: source file {source_html} does not exist.")
        return

    with open(source_html, "rb") as f:
        html_bytes = f.read()

    # Compress with maximum compression level
    gz_bytes = gzip.compress(html_bytes, compresslevel=9)

    # Format into C array
    hex_lines = []
    chunk_size = 16
    for i in range(0, len(gz_bytes), chunk_size):
        chunk = gz_bytes[i:i + chunk_size]
        hex_lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk))

    array_body = ",\n".join(hex_lines)

    content = f"""// Auto-generated by scripts/build_html.py. Do not edit directly.
#pragma once
#include <Arduino.h>

const uint8_t INDEX_HTML_GZ[] PROGMEM = {{
{array_body}
}};
const size_t INDEX_HTML_GZ_LEN = {len(gz_bytes)};
"""

    # Avoid updating mtime if the file content has not changed
    if os.path.exists(output_header):
        with open(output_header, "r", encoding="utf-8") as f:
            existing = f.read()
        if existing == content:
            return

    os.makedirs(os.path.dirname(output_header), exist_ok=True)
    with open(output_header, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"[build_html] Generated {output_header} ({len(html_bytes)} bytes -> {len(gz_bytes)} bytes gzipped)")

build_portal_header()
